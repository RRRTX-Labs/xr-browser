"""build/farm/budget_meter.py — the patch-budget meter + audit gate (P2-T10 → P3-T3).

Counts xr-core patch-manifest entries against the §1.2 budget
(build/upstream/budget-config.json, generated from the PINNED plan by
gen_budget_config.py — data-driven, never hand-edited).

P3-T3: `--gate` BLOCKS CI (was report-only in P2): total ≤ 150, per-category
caps, and — with a checkout — "unregistered diff in src/ outside src/xr
⇒ fail" (Plan §12.2). `audit` is the `xrctl patches audit` surface
(`./scripts/build audit`): drift, orphans, budget, registration.

Outputs: budget-report.json, the committed docs/state/budget.md table
( regenerated by CI; stale = fail), and `--release-note-snippet` for the
"count published in every release note" law (§12.2; the release-note
generator hook itself lands in P10).
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

for _p in [Path(__file__).resolve().parent, *Path(__file__).resolve().parents]:
    if (_p / "_common.py").exists():
        sys.path.insert(0, str(_p))
        break
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "patching"))

from _common import (  # noqa: E402
    ToolError, add_common_flags, emit, load_deps, main_with_guard, repo_root,
)
from categories import PLAN_CAPS, TOTAL_CAP  # noqa: E402

DEFAULT_MANIFEST = "../xr-core/patches/manifest.yaml"  # relative to meta repo root
STATE_DOC = "docs/state/budget.md"


def load_budget_config(root: Path) -> dict:
    cfg_path = root / "build" / "upstream" / "budget-config.json"
    if not cfg_path.exists():
        raise ToolError(f"{cfg_path} missing — run build/upstream/gen_budget_config.py")
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    if cfg.get("total_cap") != TOTAL_CAP or cfg.get("caps") != dict(PLAN_CAPS):
        raise ToolError("budget-config.json diverges from categories.py — "
                        "run build/upstream/gen_budget_config.py (plan §1.2 is law)")
    return cfg


def _load_manifest(path: Path) -> dict:
    import yaml
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except Exception as exc:
        raise ToolError(f"manifest load failure {path}: {exc}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("patches"), list):
        raise ToolError(f"{path}: not a patch manifest")
    return data


def registered_files(manifest: dict) -> set[str]:
    out: set[str] = set()
    for p in manifest.get("patches", []):
        out.update(p.get("files") or [])
    return out


def _unregistered_checkout_diff(checkout: Path, manifest: dict) -> list[str]:
    """Plan §12.2: unregistered diffs in src/ outside src/xr fail the audit.
    Scans `git status --porcelain` + staged/unstaged diffs of the src tree."""
    src = checkout / "src"
    if not (src / ".git").exists() and not (src).exists():
        raise ToolError(f"{src} is not a checkout; pass --manifest for a "
                        "manifest-only audit or a real checkout for the full audit")
    failures: list[str] = []
    r = subprocess.run(["git", "-C", str(src), "status", "--porcelain"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise ToolError(f"git status failed in {src}: {r.stderr}")
    registered = registered_files(manifest)
    for line in r.stdout.splitlines():
        code, path = line[:2], line[3:].strip('"')
        if code == "??":  # untracked: not a diff to upstream files
            continue
        if path.startswith("xr/"):  # src/xr — the XR overlay itself
            continue
        if path in registered:
            continue
        failures.append(f"unregistered diff in src/ outside src/xr: {path} "
                        f"(git status {code!r}; manifest registers {sorted(registered)})")
    return failures


def build_report(manifest: dict, cfg: dict) -> tuple[dict, str]:
    patches = manifest.get("patches") or []
    per: dict[str, int] = {c: 0 for c in PLAN_CAPS}
    for p in patches:
        cat = p.get("category")
        if cat in per:
            per[cat] += 1
    total = len(patches)
    over_categories = {c: {"count": per[c], "cap": PLAN_CAPS[c]}
                       for c in PLAN_CAPS
                       if PLAN_CAPS[c] is not None and per[c] > PLAN_CAPS[c]}
    report = {
        "tool": "budget_meter",
        "total": total,
        "per_category": per,
        "cap": TOTAL_CAP,
        "category_caps": {c: (cap if cap is not None else "unlimited") for c, cap in PLAN_CAPS.items()},
        "over_budget": total > TOTAL_CAP,
        "over_categories": over_categories,
        "config_source": cfg["source"],
    }
    md = ["| category | patches | cap |", "|---|---|---|"]
    for c, n in sorted(per.items()):
        cap = PLAN_CAPS[c]
        md.append(f"| {c} | {n} | {cap if cap is not None else 'unlimited'} |")
    md.append(f"| **total** | **{total}** | **{TOTAL_CAP}** |")
    return report, "\n".join(md) + "\n"


def state_doc_body(report: dict, table: str) -> str:
    return (
        "# Patch budget — generated state (do not edit by hand)\n\n"
        "Generated by `./scripts/build budget --state-doc docs/state/budget.md`\n"
        f"from the xr-core patch manifest at the DEPS pin. Config source: {report['config_source']}.\n\n"
        f"{table}\n"
        f"_Total {report['total']} / {report['cap']} upstream-touched files; the count is "
        "published in every release note (Plan §12.2)._ (regenerated: see git log)\n")


def main() -> None:
    parser = argparse.ArgumentParser(prog="budget_meter",
                                     description="Patch-budget meter (§1.2): report, --gate (CI-blocking), audit surface (§12.2).")
    sub = parser.add_subparsers(dest="cmd")
    meter = sub.add_parser("budget", help="count + caps")
    meter.add_argument("--manifest", default=DEFAULT_MANIFEST)
    meter.add_argument("--report-dir", default=None)
    meter.add_argument("--state-doc", default=None, help="regenerate the committed state doc (e.g. docs/state/budget.md)")
    meter.add_argument("--check-state-doc", action="store_true", help="fail if the committed state doc is stale")
    meter.add_argument("--gate", action="store_true", help="BLOCK on over-budget (CI mode; default is report-only)")
    meter.add_argument("--release-note-snippet", action="store_true",
                       help="print the release-note count line (§12.2 law: count published per release)")
    add_common_flags(meter)
    audit = sub.add_parser("audit", help="xrctl patches audit (§12.2): drift, orphans, budget, registration")
    audit.add_argument("--manifest", default=DEFAULT_MANIFEST)
    audit.add_argument("--checkout", default=None, help="checkout root (contains src/); enables the unregistered-diff scan")
    audit.add_argument("--ledger", default=None, help="applicability ledger (.xr/patch-apply.json) for orphan detection")
    audit.add_argument("--report-dir", default=None)
    add_common_flags(audit)

    # P2 called this tool without a subcommand (bare meter); keep that form
    # working by defaulting to `budget`.
    if len(sys.argv) < 2 or sys.argv[1] not in {"budget", "audit"}:
        sys.argv.insert(1, "budget")
    args = parser.parse_args()
    if args.cmd is None:  # pragma: no cover (defensive)
        args = meter.parse_args()
        args.cmd = "budget"

    def run() -> int:
        root = repo_root()
        cfg = load_budget_config(root)
        mpath = (root / args.manifest).resolve()
        if not mpath.exists():
            raise ToolError(f"manifest not found: {mpath} (xr-core rev in DEPS? run build sync)")
        manifest = _load_manifest(mpath)
        report, table = build_report(manifest, cfg)
        failures: list[str] = []

        if args.cmd == "audit":
            report["tool"] = "xr-audit"
            # orphans: ledger entries whose patch no longer exists in the manifest
            if args.ledger and Path(args.ledger).exists():
                ledger = json.loads(Path(args.ledger).read_text(encoding="utf-8"))
                ids = {p.get("id") for p in manifest.get("patches", [])}
                for lid in ledger.get("applied", {}):
                    if lid not in ids:
                        failures.append(f"orphan ledger entry: {lid} applied but not in the manifest")
            # unregistered diff scan (needs a checkout)
            if args.checkout:
                failures.extend(_unregistered_checkout_diff(Path(args.checkout), manifest))
            # every patch must be registered with owner+category (§12.2 patchinfo law is xr-patch lint's;
            # audit re-checks the manifest-level basics)
            for p in manifest.get("patches", []):
                if not p.get("owner"):
                    failures.append(f"patch {p.get('id')!r} has no owner")
                if not p.get("category") or p.get("category") not in PLAN_CAPS:
                    failures.append(f"patch {p.get('id')!r} category invalid: {p.get('category')!r}")
        else:
            if args.gate:
                if report["over_budget"]:
                    failures.append(f"budget gate: {report['total']} patches exceed the total cap {TOTAL_CAP} "
                                    "(Plan §1.2: exceeding budget = architecture review, never silent scope)")
                for c, info in report["over_categories"].items():
                    failures.append(f"budget gate: category {c!r} has {info['count']} patches, cap {info['cap']}")

        report["gate"] = bool(getattr(args, "gate", False))
        report["failures"] = failures

        if getattr(args, "state_doc", None) or getattr(args, "check_state_doc", False):
            doc = root / (getattr(args, "state_doc", None) or STATE_DOC)
            body = state_doc_body(report, table)
            if args.check_state_doc:
                if not doc.exists() or doc.read_text(encoding="utf-8") != body:
                    failures.append(f"{doc} is stale — regenerate: "
                                    "./scripts/build budget --state-doc docs/state/budget.md")
                    report["failures"] = failures
                else:
                    print(f"PASS: {STATE_DOC} fresh")
            else:
                doc.parent.mkdir(parents=True, exist_ok=True)
                doc.write_text(body, encoding="utf-8")
                print(f"state doc written: {doc}")

        if getattr(args, "release_note_snippet", False):
            report["release_note_snippet"] = (
                f"- Upstream patches carried: {report['total']} of {report['cap']} budgeted files "
                f"({', '.join(f'{c}={n}' for c, n in sorted(report['per_category'].items()) if n)}) — Plan §12.2")
            print(report["release_note_snippet"])

        if getattr(args, "report_dir", None):
            d = Path(args.report_dir)
            d.mkdir(parents=True, exist_ok=True)
            (d / "budget-report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
            (d / "budget-report.md").write_text(f"# Patch-budget report\n\n{table}", encoding="utf-8")

        if not args.json:
            print(table.rstrip())
        return emit(args.json, report, failures=failures)

    main_with_guard(run)


if __name__ == "__main__":
    main()
